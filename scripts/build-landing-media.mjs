const run = (args) => execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', ...args], { stdio: 'inherit' });

const grabFrame = (seconds) => {
    const png = join(tmpdir(), `landing-frame-${seconds}.png`);
    run(['-ss', String(seconds), '-i', video, '-frames:v', '1', png]);
    return png;
};

const exportImage = async ({ name, file, frame, crop, widths }) => {
    const input = file ?? grabFrame(frame);
    const meta = await sharp(input).metadata();
    let base = sharp(input);
    let w = meta.width;
    let h = meta.height;
    if (crop) {
        const [l, t, cw, ch] = crop;
        const region = {
            left: Math.round(l * meta.width),
            top: Math.round(t * meta.height),
            width: Math.min(Math.round(cw * meta.width), meta.width - Math.round(l * meta.width)),
            height: Math.min(Math.round(ch * meta.height), meta.height - Math.round(t * meta.height))
        };
        base = base.extract(region);
        w = region.width;
        h = region.height;
    }
    const buffer = await base.png().toBuffer();
    // Drop a size that is within 15% of the next larger one.
    const sizes = [...new Set(widths.map((target) => Math.min(target, w)))]
        .sort((a, b) => b - a)
        .filter((size, i, all) => i === 0 || size < all[i - 1] * 0.85);
    for (const size of sizes) {
        await sharp(buffer).resize({ width: size }).webp({ quality: 80, effort: 6 }).toFile(join(OUT, `${name}-${size}.webp`));
    }
    return {
        name,
        src: `/landing/${name}-${sizes[0]}.webp`,
        srcSet: sizes.map((size) => `/landing/${name}-${size}.webp ${size}w`).join(', '),
        w: sizes[0],
        h: Math.round((h * sizes[0]) / w)
    };
};

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const entries = [];
for (const image of images) {
    entries.push(await exportImage(image));
    console.log('image', image.name);
}

const body = entries
    .map(({ name, src, srcSet, w, h }) => `    '${name}': { src: '${src}', srcSet: '${srcSet}', w: ${w}, h: ${h} }`)
    .join(',\n');
writeFileSync(
    MANIFEST,
    `// Generated by scripts/build-landing-media.mjs — do not edit by hand.\n` +
        `export const images = {\n${body}\n} as const;\n\n`
);

