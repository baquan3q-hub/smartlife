import { googleApiFetch, getValidGoogleToken } from './googleAuthTokenManager';

const SHEETS_API_BASE = 'https://sheets.googleapis.com/v4/spreadsheets';
const DRIVE_API_BASE = 'https://www.googleapis.com/drive/v3/files';

const SPREADSHEET_TITLE = 'SmartLife - Dữ Liệu Ghi Chú & Lưu Trữ Cá Nhân';

// Storage keys
const STORAGE_KEYS = {
  SPREADSHEET_ID: 'smartlife_gsheets_spreadsheet_id',
  LAST_SYNC: 'smartlife_gsheets_last_sync',
  AUTO_SYNC: 'smartlife_gsheets_auto_sync',
};

// Tab names
const TAB_NAMES = {
  NOTE_ARCHIVES: 'Note Archives',
  QUICK_NOTES: 'Quick Notes',
  AI_SUMMARIES: 'AI Summaries',
};

// Headers cho mỗi tab
const TAB_HEADERS: Record<string, string[]> = {
  [TAB_NAMES.NOTE_ARCHIVES]: ['ID', 'Ngày tạo', 'Tiêu đề', 'Nhãn (Labels)', 'Nội dung chi tiết', 'Ghim', 'Cập nhật cuối'],
  [TAB_NAMES.QUICK_NOTES]: ['ID', 'Timestamp', 'Nội dung', 'Loại'],
  [TAB_NAMES.AI_SUMMARIES]: ['ID', 'Ngày', 'Loại báo cáo', 'Nội dung', 'Generated by'],
};

// ────────────────────────────────────────
// Settings
// ────────────────────────────────────────

export const isSheetsConnected = (): boolean => {
  return getValidGoogleToken() !== null;
};

export const getStoredSpreadsheetId = (): string | null => {
  if (typeof window === 'undefined') return null;
  return localStorage.getItem(STORAGE_KEYS.SPREADSHEET_ID);
};

export const isSheetsAutoSyncEnabled = (): boolean => {
  if (typeof window === 'undefined') return false;
  const stored = localStorage.getItem(STORAGE_KEYS.AUTO_SYNC);
  return stored === 'true';
};

export const setSheetsAutoSync = (enabled: boolean): void => {
  if (typeof window === 'undefined') return;
  localStorage.setItem(STORAGE_KEYS.AUTO_SYNC, enabled ? 'true' : 'false');
};

export const getLastSheetsSync = (): string | null => {
  if (typeof window === 'undefined') return null;
  return localStorage.getItem(STORAGE_KEYS.LAST_SYNC);
};

