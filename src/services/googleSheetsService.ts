/**
 * Lấy URL mở Spreadsheet trên Google Sheets
 */
export const getSpreadsheetUrl = async (): Promise<string | null> => {
  const id = getStoredSpreadsheetId();
  if (!id) return null;
  return `https://docs.google.com/spreadsheets/d/${id}/edit`;
};

/**
 * Lấy tất cả dữ liệu từ tab Note Archives
 */
export const getAllNoteArchivesFromSheets = async (): Promise<Array<{
  id: string;
  created_at: string;
  title: string;
  labels: string;
  content: string;
  is_pinned: boolean;
  updated_at: string;
}>> => {
  const spreadsheetId = await findOrCreateSpreadsheet();
  const data = await readSheetData(spreadsheetId, `'${TAB_NAMES.NOTE_ARCHIVES}'!A2:G`);

  return data.map(row => ({
    id: row[0] || '',
    created_at: row[1] || '',
    title: row[2] || '',
    labels: row[3] || '',
    content: row[4] || '',
    is_pinned: (row[5] || '').toUpperCase() === 'TRUE',
    updated_at: row[6] || '',
  }));
};
