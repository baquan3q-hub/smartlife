/**
 * Đọc dữ liệu từ 1 tab (range)
 */
export const readSheetData = async (
  spreadsheetId: string,
  range: string
): Promise<string[][]> => {
  const response = await googleApiFetch(
    `${SHEETS_API_BASE}/${spreadsheetId}/values/${encodeURIComponent(range)}`
  );

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`Sheets API readData error ${response.status}: ${err}`);
  }

  const data = await response.json();
  return data.values || [];
};

/**
 * Append dữ liệu vào cuối tab
 */
export const appendSheetData = async (
  spreadsheetId: string,
  range: string,
  values: string[][]
): Promise<void> => {
  const response = await googleApiFetch(
    `${SHEETS_API_BASE}/${spreadsheetId}/values/${encodeURIComponent(range)}:append?valueInputOption=USER_ENTERED&insertDataOption=INSERT_ROWS`,
    {
      method: 'POST',
      body: JSON.stringify({ values }),
    }
  );

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`Sheets API appendData error ${response.status}: ${err}`);
  }
};

/**
 * Update dữ liệu tại vị trí cụ thể
 */
export const updateSheetData = async (
  spreadsheetId: string,
  range: string,
  values: string[][]
): Promise<void> => {
  const response = await googleApiFetch(
    `${SHEETS_API_BASE}/${spreadsheetId}/values/${encodeURIComponent(range)}?valueInputOption=USER_ENTERED`,
    {
      method: 'PUT',
      body: JSON.stringify({ values }),
    }
  );

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`Sheets API updateData error ${response.status}: ${err}`);
  }
};

