/**
 * Sync một ghi chú vào tab "Note Archives"
 */
export const syncNoteToSheets = async (note: {
  id: string;
  title: string;
  content: string;
  labels?: string[];
  is_pinned?: boolean;
  created_at?: string;
  updated_at?: string;
}): Promise<void> => {
  const spreadsheetId = await findOrCreateSpreadsheet();

  // Check if note already exists (by ID in column A)
  const existingData = await readSheetData(spreadsheetId, `'${TAB_NAMES.NOTE_ARCHIVES}'!A:A`);
  const rowIndex = existingData.findIndex(row => row[0] === note.id);

  const row = [
    note.id,
    note.created_at || new Date().toISOString().slice(0, 10),
    note.title,
    (note.labels || []).join(', '),
    note.content,
    note.is_pinned ? 'TRUE' : 'FALSE',
    note.updated_at || new Date().toISOString().slice(0, 16).replace('T', ' '),
  ];

  if (rowIndex >= 0) {
    // Update existing row (rowIndex + 1 because Sheets is 1-indexed)
    await updateSheetData(
      spreadsheetId,
      `'${TAB_NAMES.NOTE_ARCHIVES}'!A${rowIndex + 1}:G${rowIndex + 1}`,
      [row]
    );
  } else {
    // Append new row
    await appendSheetData(spreadsheetId, `'${TAB_NAMES.NOTE_ARCHIVES}'!A:G`, [row]);
  }

  localStorage.setItem(STORAGE_KEYS.LAST_SYNC, new Date().toISOString());
};

/**
 * Sync quick note vào tab "Quick Notes"
 */
export const syncQuickNoteToSheets = async (note: {
  id: string;
  content: string;
  type?: string;
}): Promise<void> => {
  const spreadsheetId = await findOrCreateSpreadsheet();

  const row = [
    note.id,
    new Date().toISOString().slice(0, 19).replace('T', ' '),
    note.content,
    note.type || 'quick_note',
  ];

  await appendSheetData(spreadsheetId, `'${TAB_NAMES.QUICK_NOTES}'!A:D`, [row]);
  localStorage.setItem(STORAGE_KEYS.LAST_SYNC, new Date().toISOString());
};

