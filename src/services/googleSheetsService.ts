/**
 * Tìm file Spreadsheet "SmartLife - Dữ Liệu Ghi Chú & Lưu Trữ Cá Nhân" trên Drive
 * Nếu chưa có → tạo mới với 3 tabs chuẩn hóa
 */
export const findOrCreateSpreadsheet = async (): Promise<string> => {
  // 1. Check cache first
  const cachedId = getStoredSpreadsheetId();
  if (cachedId) {
    // Verify it still exists
    try {
      const response = await googleApiFetch(`${SHEETS_API_BASE}/${cachedId}?fields=spreadsheetId`);
      if (response.ok) return cachedId;
    } catch {
      // Cached ID is invalid, search again
      localStorage.removeItem(STORAGE_KEYS.SPREADSHEET_ID);
    }
  }

  // 2. Search for existing file on Drive (safely wrapped in try/catch)
  try {
    const searchQuery = `name='${SPREADSHEET_TITLE}' and mimeType='application/vnd.google-apps.spreadsheet' and trashed=false`;
    const searchResponse = await googleApiFetch(
      `${DRIVE_API_BASE}?q=${encodeURIComponent(searchQuery)}&fields=files(id,name)&pageSize=1`
    );

    if (searchResponse.ok) {
      const searchData = await searchResponse.json();
      if (searchData.files && searchData.files.length > 0) {
        const spreadsheetId = searchData.files[0].id;
        localStorage.setItem(STORAGE_KEYS.SPREADSHEET_ID, spreadsheetId);
        return spreadsheetId;
      }
    }
  } catch (driveErr) {
    console.warn('[GoogleSheets] Drive search notice (proceeding to create via Sheets API):', driveErr);
  }

  // 3. Create new spreadsheet with 3 clean tabs
  const createBody = {
    properties: {
      title: SPREADSHEET_TITLE,
    },
    sheets: [
      { properties: { title: TAB_NAMES.NOTE_ARCHIVES } },
      { properties: { title: TAB_NAMES.QUICK_NOTES } },
      { properties: { title: TAB_NAMES.AI_SUMMARIES } },
    ],
  };

  const createResponse = await googleApiFetch(SHEETS_API_BASE, {
    method: 'POST',
    body: JSON.stringify(createBody),
  });

  if (!createResponse.ok) {
    const err = await createResponse.text();
    throw new Error(`Không thể tạo Spreadsheet (${createResponse.status}): ${err}`);
  }

  const createData = await createResponse.json();
  const newId = createData.spreadsheetId;
  localStorage.setItem(STORAGE_KEYS.SPREADSHEET_ID, newId);

  // Initialize header rows for each tab in parallel
  try {
    await Promise.all([
      appendSheetData(newId, `'${TAB_NAMES.NOTE_ARCHIVES}'!A1`, [TAB_HEADERS[TAB_NAMES.NOTE_ARCHIVES]]),
      appendSheetData(newId, `'${TAB_NAMES.QUICK_NOTES}'!A1`, [TAB_HEADERS[TAB_NAMES.QUICK_NOTES]]),
      appendSheetData(newId, `'${TAB_NAMES.AI_SUMMARIES}'!A1`, [TAB_HEADERS[TAB_NAMES.AI_SUMMARIES]]),
    ]);
  } catch (headerErr) {
    console.warn('[GoogleSheets] Error writing initial headers:', headerErr);
  }

  console.info(`[GoogleSheets] Created new spreadsheet: ${newId}`);
  return newId;
};

